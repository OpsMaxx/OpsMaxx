/**
 * The environment that makes one process talk to the inspector and trust it.
 *
 * This is rung one of the whole feature and the only one that needs no
 * privilege, no system state and no cleanup: a terminal started with these
 * variables is intercepted, and one started without them is not.
 *
 * Applied to local terminals, and returned to the renderer so a person can
 * paste them into a shell of their own — including a remote one. It is
 * deliberately not pushed down an SSH channel: `sshd` drops every variable but
 * `LANG` and `LC_*` by default and reports nothing when it does, so that path
 * would look like it worked and capture nothing.
 *
 * The CA path variables are as important as the proxy ones. Node, Python's
 * `requests` and Go all carry their own trust store and ignore the system
 * one — which is the real reason most "this app pins its certificate" reports
 * are not about pinning at all.
 */
export function inspectEnv(): InspectEnv {
  const current = run
  if (!current || !ca) return {}
  // A listener bound to 0.0.0.0 is still reached from this machine over
  // loopback, and handing a process the literal 0.0.0.0 as a proxy address is
  // how a working proxy looks broken.
  const host = current.bindHost === '0.0.0.0' ? '127.0.0.1' : current.bindHost
  // Credentials go in the URL because that is the only place an environment
  // variable can carry them, and every client that reads HTTPS_PROXY
  // understands the form.
  const auth = current.credentials
    ? `${encodeURIComponent(current.credentials.username)}:${encodeURIComponent(current.credentials.password)}@`
    : ''
  const url = `http://${auth}${host}:${current.bindPort}`
  const certPath = ca.certPath
  return {
    HTTP_PROXY: url,
    HTTPS_PROXY: url,
    http_proxy: url,
    https_proxy: url,
    // Without this, every request to the machine's own services would be
    // bounced through the proxy — which usually works and occasionally
    // deadlocks, when the service being called is OpsMaxx itself.
    NO_PROXY: 'localhost,127.0.0.1,::1',
    no_proxy: 'localhost,127.0.0.1,::1',
    NODE_EXTRA_CA_CERTS: certPath,
    REQUESTS_CA_BUNDLE: certPath,
    SSL_CERT_FILE: certPath,
    CURL_CA_BUNDLE: certPath,
    // Go reads neither of the above. It reads this.
    GIT_SSL_CAINFO: certPath
  }
}

/** True when a new session should be given the inspector's environment. */
export function inspectInjectsSessions(): boolean {
  return !!run && run.source === 'sessions'
}
